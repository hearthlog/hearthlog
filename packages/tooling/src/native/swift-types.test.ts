import assert from 'node:assert/strict';
import { test } from 'node:test';

import { Type } from '@sinclair/typebox';

import { camelCase, pascalCase, swiftTypes, SwiftTypesError, type ContractShape } from './swift-types.js';

const origin = { moduleId: 'org.example.notes', contractFile: 'src/native/contract.ts' };

const Note = Type.Object({
    id: Type.String(),
    title: Type.String(),
    created_at: Type.String(),
    pinned: Type.Boolean(),
    words: Type.Integer(),
    score: Type.Number(),
    folder: Type.Union([Type.String(), Type.Null()]),
    tags: Type.Array(Type.String()),
    kind: Type.Union([Type.Literal('text'), Type.Literal('check-list'), Type.Literal('default')], { $id: 'NoteKind' }),
    extra: Type.Record(Type.String(), Type.Integer()),
}, { $id: 'Note' });

const contract: ContractShape = {
    namespace: 'notes',
    version: 2,
    queries: {
        count: { args: Type.Object({}), result: Type.Object({ total: Type.Integer() }), depends: ['app:notes'] },
        'notes.list': { args: Type.Object({ page: Type.Integer(), q: Type.Optional(Type.String()) }), result: Type.Array(Note), depends: ['app:notes'] },
        'notes.get': { args: Type.Object({ id: Type.String() }), result: Note, depends: [] },
    },
};

test('names follow Swift conventions', () => {
    assert.equal(pascalCase('scenes list'), 'ScenesList');
    assert.equal(pascalCase('created_at'), 'CreatedAt');
    assert.equal(camelCase('created_at'), 'createdAt');
    assert.equal(camelCase('check-list'), 'checkList');
    assert.equal(camelCase('performerId'), 'performerId');
});

test('a contract becomes one enum with typed queries and Codable types', () => {
    const source = swiftTypes(contract, origin);
    assert.match(source, /^\/\/ AUTO-GENERATED by `hearthlog apple:types` from org\.example\.notes \(src\/native\/contract\.ts\)\. Do not edit\./);
    assert.match(source, /enum Notes \{\n {4}static let namespace = "notes"\n {4}static let version = 2\n/);
    assert.match(source, /static let count = EngineQuery<NoArguments, Notes\.CountResult>\(name: "notes\.count", depends: \["app:notes"\]\)/);
    assert.match(source, /enum Notes \{[\s\S]*?\n {4}enum Notes \{\n {8}static let get = EngineQuery<Notes\.NotesGetArguments, Notes\.Note>\(name: "notes\.notes\.get", depends: \[\]\)\n {8}static let list = EngineQuery<Notes\.NotesListArguments, \[Notes\.Note\]>/);
    assert.match(source, /struct Note: Codable, Equatable, Hashable, Sendable, Identifiable \{/);
    assert.match(source, /var createdAt: String\n/);
    assert.match(source, /case createdAt = "created_at"/);
    assert.match(source, /var folder: String\?\n/);
    assert.match(source, /var tags: \[String\]\n/);
    assert.match(source, /var extra: \[String: Int\]\n/);
    assert.match(source, /var score: Double\n/);
    assert.match(source, /enum NoteKind: String, Codable, Hashable, Sendable, CaseIterable \{\n {8}case text\n {8}case checkList = "check-list"\n {8}case `default`\n {4}\}/);
    assert.match(source, /struct NotesListArguments: Codable, Equatable, Hashable, Sendable \{\n {8}var page: Int\n {8}var q: String\?\n {4}\}/);
    // A named schema used twice is declared once.
    assert.equal(source.match(/struct Note:/g)?.length, 1);
});

test('the output is stable', () => {
    assert.equal(swiftTypes(contract, origin), swiftTypes(contract, origin));
});

test('schemas Swift cannot say are refused with where they are', () => {
    const union = { namespace: 'notes', version: 1, queries: { get: { args: Type.Object({}), result: Type.Union([Type.String(), Type.Integer()]), depends: [] } } };
    assert.throws(() => swiftTypes(union, origin), (error: unknown) => error instanceof SwiftTypesError && /get result: a union/.test(error.message));
    const clash = {
        namespace: 'notes', version: 1,
        queries: {
            a: { args: Type.Object({}), result: Type.Object({ x: Type.String() }, { $id: 'Same' }), depends: [] },
            b: { args: Type.Object({}), result: Type.Object({ y: Type.String() }, { $id: 'Same' }), depends: [] },
        },
    };
    assert.throws(() => swiftTypes(clash, origin), /two different schemas are named Same/);
});
