#!/usr/bin/env npx tsx
/**
 * JSON Schema for tenants.json, so editors validate and complete it.
 *
 * Feature ids, AI capabilities and integration kinds come from the code, so
 * the schema is generated rather than hand-written. `tenant-config.ts` stays
 * the authoritative validator; the schema only mirrors its shape for IDEs.
 *
 * Usage: pnpm generate:tenant-schema [--check]
 */

import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { FEATURES } from "@hearthlog/contracts/features/registry";
import { AI_CAPABILITIES } from "@hearthlog/contracts/ai/capabilities";
import { INTEGRATION_ID_PATTERN, INTEGRATION_KINDS } from "@hearthlog/contracts/integrations/kinds";
import { DEVELOPER_PATH, REPOSITORY_ROOT } from "./tenant-config.js";

export const TENANT_SCHEMA_FILE = join(REPOSITORY_ROOT, "tenants.schema.json");

const nonEmptyString = { type: "string", minLength: 1 };
const httpsOrigin = { type: "string", pattern: "^https://[^/?#@]+/?$" };
const hours = { type: "string", pattern: "^[1-9][0-9]*h$", description: "Whole hours between 1h and 720h." };

export function buildTenantSchema(): Record<string, unknown> {
    const featureIds = FEATURES.map((feature) => feature.id);
    const homePaths = [...new Set(["/", DEVELOPER_PATH, ...FEATURES.flatMap((feature) => feature.page ? [feature.page.path] : [])])];
    const shared = {
        features: {
            type: "array",
            items: { enum: featureIds },
            minItems: 1,
            uniqueItems: true,
        },
        home: { enum: homePaths, description: "Start path; must belong to an enabled feature." },
        title: nonEmptyString,
        developerNavVisible: { type: "boolean" },
        entitiesNavVisible: { type: "boolean" },
    };
    return {
        $schema: "http://json-schema.org/draft-07/schema#",
        title: "Hearthlog tenants",
        description: "Generated by packages/tooling/src/tenants/tenant-schema.ts; do not edit by hand.",
        type: "object",
        additionalProperties: false,
        required: ["infrastructure"],
        properties: {
            $schema: { type: "string" },
            infrastructure: {
                type: "object",
                additionalProperties: false,
                required: [
                    "ledgerWorker",
                    "invoicePdfsBucket",
                    "calendarFeedsBucket",
                    "calendarPublicWorker",
                    "calendarPublicOrigin",
                    "galleryFilesBucket",
                    "galleryPublicBucket",
                    "galleryPublicWorker",
                    "galleryPublicOrigin",
                    "workersDevDomain",
                    "ledgerAdminEmail",
                    "accessTeamDomain",
                ],
                properties: {
                    ledgerWorker: nonEmptyString,
                    invoicePdfsBucket: nonEmptyString,
                    calendarFeedsBucket: nonEmptyString,
                    calendarPublicWorker: nonEmptyString,
                    calendarPublicOrigin: httpsOrigin,
                    galleryFilesBucket: nonEmptyString,
                    galleryPublicBucket: nonEmptyString,
                    galleryPublicWorker: nonEmptyString,
                    galleryPublicOrigin: httpsOrigin,
                    workersDevDomain: { type: "string", pattern: "^[a-z0-9][a-z0-9-]*\\.workers\\.dev$", description: "The account's workers.dev subdomain." },
                    invoiceRendererOrigin: httpsOrigin,
                    kalApiOrigin: httpsOrigin,
                    ledgerAdminEmail: { type: "string", format: "email" },
                    accessTeamDomain: httpsOrigin,
                    accessSessionDuration: hours,
                    accessGlobalSessionDuration: hours,
                    accountId: { type: "string", pattern: "^[0-9a-f]{32}$", description: "The Cloudflare account that holds the shared stack." },
                    gallerySweeper: { type: "string", description: "The shared-stack site that sweeps the public Gallery bucket; the first by id when unset." },
                },
            },
            defaults: {
                type: "object",
                additionalProperties: false,
                properties: shared,
            },
            sites: {
                type: "array",
                items: {
                    type: "object",
                    additionalProperties: false,
                    required: ["id", "authorizedEmails"],
                    properties: {
                        id: {
                            type: "string",
                            pattern: "^[a-z0-9][a-z0-9-]*$",
                            description: "Becomes the wrangler env, the Worker name and the workers.dev hostname.",
                        },
                        ledgerAppName: nonEmptyString,
                        admin: { type: "boolean" },
                        authorizedEmails: {
                            type: "array",
                            items: { type: "string", format: "email" },
                            minItems: 1,
                            uniqueItems: true,
                        },
                        ...shared,
                        ai: {
                            type: "array",
                            items: { enum: [...AI_CAPABILITIES] },
                            uniqueItems: true,
                        },
                        integrations: {
                            type: "array",
                            items: {
                                type: "object",
                                additionalProperties: false,
                                required: ["id", "kind", "logId"],
                                properties: {
                                    id: { type: "string", pattern: INTEGRATION_ID_PATTERN.source },
                                    kind: { enum: [...INTEGRATION_KINDS] },
                                    logId: { type: "string", format: "uuid" },
                                    clientId: { type: "string", description: "Access service-token client id; inactive until set." },
                                },
                            },
                        },
                        dynamicEntities: { type: "boolean" },
                        theme: {
                            type: "object",
                            additionalProperties: false,
                            properties: {
                                accent: { type: "string", pattern: "^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$" },
                            },
                        },
                        hostname: { type: "string", format: "uri" },
                    },
                },
            },
        },
    };
}

export function renderTenantSchema(): string {
    return `${JSON.stringify(buildTenantSchema(), null, 2)}\n`;
}

/** Whether tenants.schema.json matches the code it is generated from. */
export async function isTenantSchemaCurrent(): Promise<boolean> {
    const current = await readFile(TENANT_SCHEMA_FILE, "utf8").catch(() => "");
    return current === renderTenantSchema();
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    if (process.argv.includes("--check")) {
        if (!(await isTenantSchemaCurrent())) {
            console.error("tenants.schema.json is stale; run pnpm generate:tenant-schema");
            process.exit(1);
        }
        console.log("tenants.schema.json is current.");
    } else {
        await writeFile(TENANT_SCHEMA_FILE, renderTenantSchema());
        console.log("Generated tenants.schema.json");
    }
}
