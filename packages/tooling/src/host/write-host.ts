#!/usr/bin/env npx tsx
/**
 * Write the host files every site shares into the gitignored `.generated/`, for the SvelteKit app:
 *
 *   routes/            the core routes (a table in this package) and the site's own `src/routes/`;
 *                      `pnpm build:generated` composes the site's module routes into `routes/(modules)/` afterwards
 *   app.css            Tailwind, the design system's and the shell's styles, the enabled modules' stylesheets
 *   service-worker/    the entry SvelteKit bundles as the service worker (the code is `@hearthlog/shell`)
 *   app.d.ts, microlighter.d.ts   ambient types
 *   tsconfig.json      the paths a site's tsconfig extends (`$tenant/generated` is the site's tenant module)
 *   static/            the shell's core static files and the site's own `static/`, with only this site's icons
 *
 * Usage: pnpm build:generated (runs this after the catalog is written)
 */

import { existsSync, readdirSync, statSync } from "node:fs";
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { activeSiteId, hostRoot } from "../root.js";
import { CORE_ROUTE_FILES } from "./core-routes.js";

const ROOT = hostRoot();
const GENERATED = join(ROOT, ".generated");
const TEMPLATES = resolve(dirname(fileURLToPath(import.meta.url)), "../../templates/host");

/** The directory of an installed package, found from the host so a site resolves its own copy. */
export function packageDirectory(name: string): string {
    return dirname(createRequire(join(ROOT, "package.json")).resolve(`${name}/package.json`));
}

export function renderAppCss(hasSiteSources: boolean): string {
    return [
        "/* AUTO-GENERATED by packages/tooling/src/host/write-host.ts. Do not edit. */",
        "@import 'tailwindcss' source('./');",
        "@import '@hearthlog/ui/styles/index.css';",
        "@import '@hearthlog/shell/styles/index.css';",
        "/* The enabled modules' stylesheets and Tailwind sources: written beside this file by the composer. */",
        "@import './module-sources.generated.css';",
        // The generated folder is gitignored, which Tailwind's automatic detection honours; name its routes.
        "@source './routes';",
        ...(hasSiteSources ? ["@source '../src';"] : []),
        "",
    ].join("\n");
}

export function renderServiceWorkerEntry(): string {
    return [
        "// AUTO-GENERATED by packages/tooling/src/host/write-host.ts. Do not edit.",
        "// SvelteKit bundles this reserved entry as the service worker; the code is the shell's.",
        "import '@hearthlog/shell/service-worker/index.js';",
        "",
    ].join("\n");
}

function filesIn(directory: string): string[] {
    if (!existsSync(directory)) return [];
    return readdirSync(directory, { withFileTypes: true }).filter((entry) => entry.name !== ".DS_Store").flatMap((entry) => {
        const path = join(directory, entry.name);
        return entry.isDirectory() ? filesIn(path) : [path];
    });
}

async function writeRoutes(): Promise<void> {
    const routes = join(GENERATED, "routes");
    await rm(routes, { recursive: true, force: true });
    const written = new Set<string>();
    for (const { path, content } of CORE_ROUTE_FILES) {
        await mkdir(dirname(join(routes, path)), { recursive: true });
        await writeFile(join(routes, path), content, "utf8");
        written.add(path);
    }
    const own = join(ROOT, "src", "routes");
    for (const file of filesIn(own)) {
        const path = relative(own, file).split(sep).join("/");
        if (path.startsWith("(modules)/")) throw new Error(`src/routes/${path}: the (modules) group belongs to the composed module routes`);
        if (written.has(path)) throw new Error(`src/routes/${path} collides with a core route`);
        await mkdir(dirname(join(routes, path)), { recursive: true });
        await cp(file, join(routes, path));
    }
}

async function writeStatic(siteId: string): Promise<void> {
    const target = join(GENERATED, "static");
    await rm(target, { recursive: true, force: true });
    await cp(join(packageDirectory("@hearthlog/shell"), "static"), target, { recursive: true });
    // The host's own `static/` is shared by every site; the site's `tenants/<id>/static/` (its icon set, any other
    // brand file) lands on top of it at the same paths.
    for (const own of [join(ROOT, "static"), join(ROOT, "tenants", siteId, "static")]) {
        for (const file of filesIn(own)) {
            const path = relative(own, file).split(sep).join("/");
            await mkdir(dirname(join(target, path)), { recursive: true });
            await cp(file, join(target, path));
        }
    }
}

export async function writeHost(siteId: string): Promise<void> {
    await writeRoutes();
    await writeFile(join(GENERATED, "app.css"), renderAppCss(existsSync(join(ROOT, "src")) && statSync(join(ROOT, "src")).isDirectory()), "utf8");
    await mkdir(join(GENERATED, "service-worker"), { recursive: true });
    await writeFile(join(GENERATED, "service-worker", "index.ts"), renderServiceWorkerEntry(), "utf8");
    await writeFile(join(GENERATED, "service-worker", "tsconfig.json"), `${JSON.stringify({ extends: "$app/tsconfig/service-worker" }, null, "\t")}\n`, "utf8");
    for (const name of ["app.d.ts", "microlighter.d.ts"]) {
        await writeFile(join(GENERATED, name), await readFile(join(TEMPLATES, `${name}.txt`), "utf8"), "utf8");
    }
    await writeFile(join(GENERATED, "tsconfig.json"), `${JSON.stringify({ compilerOptions: { paths: { "$tenant/generated": [`./sites/${siteId}/tenant.ts`] } } }, null, "\t")}\n`, "utf8");
    await writeStatic(siteId);
    console.log(`Wrote the host files for ${siteId}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    writeHost(activeSiteId()).catch((error: unknown) => {
        console.error(error instanceof Error ? error.message : String(error));
        process.exitCode = 1;
    });
}
