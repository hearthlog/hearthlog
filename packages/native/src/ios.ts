#!/usr/bin/env npx tsx
/**
 * Prepare the iPhone app for one site: writes .apple-build/project/Generated (Info.plist, build
 * settings, icon) and .apple-build/project/Stor.xcodeproj. Then open the project in Xcode and run it, or build and install it with
 * `hearthlog apple:resign --force`, which also keeps a free-signed build from expiring.
 *
 * Usage: hearthlog apple:ios <site>
 *
 * Everything written here is generated, in the git-ignored `.apple-build/`. See docs/native-shell.md.
 */

import { mkdirSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import path from "node:path";

import { writeXcodeProject } from "./project.js";
import {
    AppleError,
    BUILD_ROOT,
    iosInfoPlist,
    loadAppleSettings,
    loadAppleSite,
    PROJECT_ROOT,
    renderIcons,
    run,
    type AppleSettings,
    type AppleSite,
} from "./site.js";

export const GENERATED_DIRECTORY = path.join(PROJECT_ROOT, "Generated");

/**
 * Apple's team id sits in the Organizational Unit of your Apple Development certificate, which Xcode
 * creates the first time you sign in and build. Returns null when there is none or more than one.
 */
export function detectTeam(): string | null {
    let pem: string;
    try {
        pem = run("security", ["find-certificate", "-a", "-c", "Apple Development", "-p"], { quiet: true });
    } catch {
        return null;
    }
    const teams = new Set<string>();
    for (const certificate of pem.match(/-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----/g) ?? []) {
        try {
            const subject = run("openssl", ["x509", "-noout", "-subject"], { input: certificate, quiet: true });
            const team = /OU\s*=\s*([A-Z0-9]{10})\b/.exec(subject)?.[1];
            if (team) teams.add(team);
        } catch {
            // A certificate we cannot read is not one we can use.
        }
    }
    return teams.size === 1 ? [...teams][0]! : null;
}

function xcconfig(site: AppleSite, team: string): string {
    return `// Generated by @hearthlog/native (ios.ts) for site "${site.id}". Do not edit; run hearthlog apple:ios ${site.id}.
STOR_SITE = ${site.id}
PRODUCT_BUNDLE_IDENTIFIER = ${site.bundleId}
MARKETING_VERSION = ${site.version}
CURRENT_PROJECT_VERSION = ${site.build}
${team ? `DEVELOPMENT_TEAM = ${team}\n` : "// No team found: choose yours under Signing & Capabilities, or set \"team\" in resign.local.json.\n"}`;
}

/**
 * Writes the site's Info.plist, build settings and icon, and the project that uses them. Returns the
 * team id, or an empty string when there is none yet: Xcode can still open the project and ask for a
 * team, but an unattended build (`requireTeam`) cannot.
 */
export async function prepareIosSite(site: AppleSite, settings: AppleSettings, options: { requireTeam?: boolean } = {}): Promise<string> {
    const team = settings.team || detectTeam() || "";
    if (!team && options.requireTeam) {
        throw new AppleError(
            'No Apple team found. Build the app once from Xcode (hearthlog apple:ios <site>, then Run), which creates your development certificate, or set "team" in resign.local.json.',
        );
    }
    const { ios } = await renderIcons(site, path.join(BUILD_ROOT, "icons", site.id));

    rmSync(GENERATED_DIRECTORY, { recursive: true, force: true });
    const iconset = path.join(GENERATED_DIRECTORY, "Assets.xcassets", "AppIcon.appiconset");
    mkdirSync(iconset, { recursive: true });
    writeFileSync(path.join(GENERATED_DIRECTORY, "Assets.xcassets", "Contents.json"), `${JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2)}\n`);
    copyFileSync(ios, path.join(iconset, "icon-1024.png"));
    writeFileSync(
        path.join(iconset, "Contents.json"),
        `${JSON.stringify({ images: [{ filename: "icon-1024.png", idiom: "universal", platform: "ios", size: "1024x1024" }], info: { author: "xcode", version: 1 } }, null, 2)}\n`,
    );
    writeFileSync(path.join(GENERATED_DIRECTORY, "Info-iOS.plist"), iosInfoPlist(site));
    writeFileSync(path.join(GENERATED_DIRECTORY, "Site.xcconfig"), xcconfig(site, team));
    writeXcodeProject();
    return team;
}

async function main() {
    const siteId = process.argv.slice(2).find((arg) => !arg.startsWith("--"));
    if (!siteId) throw new AppleError("Usage: hearthlog apple:ios <site>");
    const settings = loadAppleSettings({ requireDevice: false });
    const site = await loadAppleSite(siteId, settings);
    const team = await prepareIosSite(site, settings);
    console.log(`Prepared ${site.title} for iOS: ${site.bundleId}, ${team ? `team ${team}` : "no team yet"}, opens ${site.origin}.`);
    if (!team) console.log("No Apple team was found. In Xcode, pick your Personal Team under Signing & Capabilities, run once, then run this again.");
    console.log(`Open ${path.relative(process.cwd(), path.join(PROJECT_ROOT, "Stor.xcodeproj"))} in Xcode and run the "Stor iOS" scheme,`);
    console.log("or build and install over the network with: hearthlog apple:resign --force");
}

if (import.meta.url === new URL(process.argv[1] ?? "", "file://").href) {
    try {
        await main();
    } catch (error) {
        console.error(`Failed: ${error instanceof Error ? error.message : String(error)}`);
        process.exitCode = 1;
    }
}
